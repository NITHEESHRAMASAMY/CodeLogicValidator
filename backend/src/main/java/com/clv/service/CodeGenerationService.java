    private String generateBinarySearchCode(String title, String comments, String lang) {
        return switch (lang) {
            case "java" -> """
                    public class Solution {
                        // Verified CLV Logic for: %s
                    %s
                        public static int binarySearch(int[] arr, int target) {
                            int low = 0, high = arr.length - 1;
                            while (low <= high) {
                                int mid = low + (high - low) / 2;
                                if (arr[mid] == target) return mid;
                                else if (arr[mid] < target) low = mid + 1;
                                else high = mid - 1;
                            }
                            return -1;
                        }

                        public static void main(String[] args) {
                            int[] arr = {2, 5, 8, 12, 16};
                            System.out.println("Index of 12: " + binarySearch(arr, 12));
                        }
                    }
                    """.formatted(title, comments);

            default -> """
                    # Verified CLV Logic for: %s
                    %s
                    def binary_search(arr: list, target: int) -> int:
                        low, high = 0, len(arr) - 1
                        while low <= high:
                            mid = (low + high) // 2
                            if arr[mid] == target:
                                return mid
                            elif arr[mid] < target:
                                low = mid + 1
                            else:
                                high = mid - 1
                        return -1

                    if __name__ == "__main__":
                        print("Index of 12:", binary_search([2, 5, 8, 12, 16], 12))
                    """.formatted(title, comments.replace("//", "#"));
        };
    }

    private String generateArithmeticOrGeneralCode(String title, String comments, List<String> lines, String lang) {
        List<String> assignStmts = new ArrayList<>();
        String printTarget = "result";

        for (String line : lines) {
            String lower = line.toLowerCase();
            if (lower.contains("=") && !lower.contains("==")) {
                assignStmts.add(line.replaceAll(";", "").trim());
            } else if (lower.startsWith("print") || lower.startsWith("output") || lower.startsWith("display") || lower.startsWith("return")) {
                printTarget = line.replaceAll("(?i)^(print|output|display|show|return)\\s*", "").replaceAll(";", "").trim();
            }
        }

        StringBuilder codeBodyJava = new StringBuilder();
        StringBuilder codeBodyPy = new StringBuilder();
        StringBuilder codeBodyCpp = new StringBuilder();
        StringBuilder codeBodyJs = new StringBuilder();

        if (assignStmts.isEmpty()) {
            codeBodyJava.append("        int a = 5;\n        int b = 7;\n        int result = a + b;\n");
            codeBodyPy.append("    a = 5\n    b = 7\n    result = a + b\n");
            codeBodyCpp.append("    int a = 5;\n    int b = 7;\n    int result = a + b;\n");
            codeBodyJs.append("  let a = 5;\n  let b = 7;\n  let result = a + b;\n");
            printTarget = "result";
        } else {
            for (String stmt : assignStmts) {
                String clean = stmt.replaceAll("(?i)^(let|var|const|int|double|float)\\s+", "").trim();
                codeBodyJava.append("        int ").append(clean).append(";\n");
                codeBodyCpp.append("    int ").append(clean).append(";\n");
                codeBodyJs.append("  let ").append(clean).append(";\n");
                codeBodyPy.append("    ").append(clean).append("\n");
            }
        }

        return switch (lang) {
            case "java" -> """
                    public class Solution {
                        // Verified CLV Logic for: %s
                    %s
                        public static void main(String[] args) {
                    %s
                            System.out.println("Result: " + %s);
                        }
                    }
                    """.formatted(title, comments, codeBodyJava.toString(), printTarget);

            case "python3", "python" -> """
                    # Verified CLV Logic for: %s
                    %s
                    def solve():
                    %s
                        print("Result:", %s)

                    if __name__ == "__main__":
                        solve()
                    """.formatted(title, comments.replace("//", "#"), codeBodyPy.toString(), printTarget);

            case "cpp" -> """
                    #include <iostream>
                    using namespace std;

                    // Verified CLV Logic for: %s
                    %s
                    int main() {
                    %s
                        cout << "Result: " << %s << endl;
                        return 0;
                    }
                    """.formatted(title, comments, codeBodyCpp.toString(), printTarget);

            case "javascript", "typescript" -> """
                    // Verified CLV Logic for: %s
                    %s
                    function solve() {
                    %s
                      console.log("Result:", %s);
                    }

                    solve();
                    """.formatted(title, comments, codeBodyJs.toString(), printTarget);

            default -> """
                    package main
                    import "fmt"

                    // Verified CLV Logic for: %s
                    %s
                    func main() {
                    %s
                        fmt.Println("Result:", %s)
                    }
                    """.formatted(title, comments, codeBodyJava.toString().replace("int ", ""), printTarget);
        };
    }
