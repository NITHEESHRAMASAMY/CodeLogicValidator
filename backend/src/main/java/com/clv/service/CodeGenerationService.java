    public CodeGenerateResponse generateCode(CodeGenerateRequest request) {
        Problem problem = problemRepository.findById(request.getProblemId()).orElse(null);
        String problemId = request.getProblemId() != null ? request.getProblemId().toLowerCase() : "";
        String title = problem != null ? problem.getTitle() : "Logic Algorithm";
        String lang = request.getLanguage().toLowerCase();
        String logicText = request.getLogicText() != null ? request.getLogicText().trim() : "";

        // 1. Try LLM code generation first if API key is configured
        String llmCode = llmEvaluationService.generateCodeWithLlm(problem, logicText, lang);
        if (llmCode != null && !llmCode.isBlank()) {
            return CodeGenerateResponse.builder()
                    .language(request.getLanguage())
                    .code(llmCode)
                    .explanation("Syntactically valid " + request.getLanguage().toUpperCase() + " implementation generated by Gemini AI from your approved logic.")
                    .build();
        }

        // 2. Synthesize code dynamically strictly based on user-given logic and user keywords
        String code = synthesizeCodeFromUserLogic(problemId, title, logicText, lang);

        return CodeGenerateResponse.builder()
                .language(request.getLanguage())
                .code(code.strip())
                .explanation("Syntactically correct " + request.getLanguage().toUpperCase() + " implementation converted directly from your approved logic reasoning.")
                .build();
    }

    /**
     * Translates the student's step-by-step logic and keywords directly into source code.
     */
    private String synthesizeCodeFromUserLogic(String problemId, String title, String logicText, String lang) {
        String[] rawLines = logicText.split("\n");
        List<String> cleanLines = new ArrayList<>();
        StringBuilder commentBlock = new StringBuilder();

        for (String line : rawLines) {
            String trimmed = line.trim();
            if (trimmed.isEmpty()) continue;
            String stripped = trimmed.replaceAll("^[0-9]+[.)\\s]+", "");
            cleanLines.add(stripped);
            commentBlock.append("    // ").append(stripped).append("\n");
        }

        String fullTextLower = logicText.toLowerCase();

        // -------------------------------------------------------------
        // Case 1: Multi-number comparison (e.g., Maximum of Three Numbers)
        // -------------------------------------------------------------
        if (fullTextLower.contains("greater") || fullTextLower.contains("compare") || fullTextLower.contains("maximum") || problemId.contains("103")) {
            // Extract variable names from student logic (e.g. X, Y, Z or A, B, C)
            List<String> vars = extractComparisonVariables(logicText);
            String v1 = vars.size() > 0 ? vars.get(0) : "X";
            String v2 = vars.size() > 1 ? vars.get(1) : "Y";
            String v3 = vars.size() > 2 ? vars.get(2) : "Z";

            return generateComparisonCode(title, commentBlock.toString(), v1, v2, v3, lang);
        }

        // -------------------------------------------------------------
        // Case 2: Even or Odd conditional branching
        // -------------------------------------------------------------
        if (fullTextLower.contains("even") || fullTextLower.contains("odd") || fullTextLower.contains("modulo") || fullTextLower.contains("remainder") || problemId.contains("102")) {
            String varName = extractSingleVariable(logicText, "N");
            return generateEvenOddCode(title, commentBlock.toString(), varName, lang);
        }

        // -------------------------------------------------------------
        // Case 3: Array Reversal / Two-Pointer Algorithm
        // -------------------------------------------------------------
        if (fullTextLower.contains("swap") || fullTextLower.contains("pointer") || fullTextLower.contains("reverse") || problemId.contains("201")) {
            String ptr1 = fullTextLower.contains("start") ? "start" : "left";
            String ptr2 = fullTextLower.contains("end") || fullTextLower.contains("finish") ? "right" : "right";
            String arrName = fullTextLower.contains("numbers") ? "numbers" : "arr";
            return generateArrayReversalCode(title, commentBlock.toString(), ptr1, ptr2, arrName, lang);
        }

        // -------------------------------------------------------------
        // Case 4: Binary Search Algorithm
        // -------------------------------------------------------------
        if (fullTextLower.contains("binary search") || fullTextLower.contains("mid") || problemId.contains("202")) {
            return generateBinarySearchCode(title, commentBlock.toString(), lang);
        }

        // -------------------------------------------------------------
        // Case 5: Direct Variable Assignments & Arithmetic Logic
        // -------------------------------------------------------------
        return generateArithmeticOrGeneralCode(title, commentBlock.toString(), cleanLines, lang);
    }

    private List<String> extractComparisonVariables(String text) {
        List<String> found = new ArrayList<>();
        Pattern pattern = Pattern.compile("\\b([A-Za-z])\\b");
        Matcher matcher = pattern.matcher(text);
        while (matcher.find()) {
            String v = matcher.group(1);
            if (!v.equalsIgnoreCase("a") && !v.equalsIgnoreCase("i") && !found.contains(v)) {
                found.add(v);
            }
        }
        if (found.size() < 3) {
            // Check for names like X, Y, Z explicitly
            for (String candidate : List.of("X", "Y", "Z", "A", "B", "C", "num1", "num2", "num3")) {
                if (text.contains(candidate) && !found.contains(candidate)) {
                    found.add(candidate);
                }
            }
        }
        if (found.isEmpty()) {
            found = List.of("X", "Y", "Z");
        }
        return found;
    }

    private String extractSingleVariable(String text, String defaultVar) {
        Pattern pattern = Pattern.compile("\\b([A-Za-z][A-Za-z0-9_]*)\\b");
        Matcher matcher = pattern.matcher(text);
        while (matcher.find()) {
            String v = matcher.group(1);
            if (!List.of("read", "input", "check", "if", "else", "otherwise", "print", "is", "even", "odd", "the", "number", "integer").contains(v.toLowerCase())) {
                return v;
            }
        }
        return defaultVar;
    }

